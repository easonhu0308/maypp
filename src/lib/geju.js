function canonicalKey(starNames) {
  return [...starNames].sort((a, b) => STAR_ORDER.indexOf(a) - STAR_ORDER.indexOf(b)).join('·');
}

export function describePattern(starNames) {
  if (!starNames || starNames.length === 0) return FALLBACK_TEXT;
  const key = canonicalKey(starNames);
  if (COMBO_TEXT[key]) return COMBO_TEXT[key];
  if (SINGLE_TEXT[starNames[0]]) return SINGLE_TEXT[starNames[0]];
  return FALLBACK_TEXT;
}
